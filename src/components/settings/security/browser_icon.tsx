const BROWSER_GLYPHS: Record<string, (props: { className?: string }) => JSX.Element> = {
  chrome: ChromeGlyph,
  firefox: FirefoxGlyph,
  safari: SafariGlyph,
  brave: BraveGlyph,
  edge: EdgeGlyph,
  opera: OperaGlyph,
  vivaldi: VivaldiGlyph,
  duckduckgo: DuckDuckGoGlyph,
};

function match_browser_key(browser: string): string | null {
  const lower = browser.toLowerCase();
  if (lower.includes("edge")) return "edge";
  if (lower.includes("chrome") || lower.includes("chromium")) return "chrome";
  if (lower.includes("firefox")) return "firefox";
  if (lower.includes("safari")) return "safari";
  if (lower.includes("brave")) return "brave";
  if (lower.includes("opera")) return "opera";
  if (lower.includes("vivaldi")) return "vivaldi";
  if (lower.includes("duckduckgo")) return "duckduckgo";
  return null;
}

interface BrowserIconProps {
  browser: string;
  className?: string;
}

export function BrowserIcon({ browser, className }: BrowserIconProps) {
  const key = match_browser_key(browser);
  const Glyph = key ? BROWSER_GLYPHS[key] : null;

  if (!Glyph) {
    return <GlobeAltIcon className={className} />;
  }

  return <Glyph className={className} />;
}
